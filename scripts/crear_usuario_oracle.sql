-- Ejecutar como SYS en el contenedor local. No modifica usuarios existentes.
WHENEVER SQLERROR EXIT SQL.SQLCODE
SET VERIFY OFF
ACCEPT autoandes_password CHAR PROMPT 'Contraseña para AUTOANDESDB: ' HIDE
ALTER SESSION SET CONTAINER = FREEPDB1;
DECLARE
    existentes NUMBER;
BEGIN
    SELECT COUNT(*) INTO existentes FROM dba_users WHERE username = 'AUTOANDESDB';
    IF existentes = 0 THEN
        EXECUTE IMMEDIATE 'CREATE USER AUTOANDESDB IDENTIFIED BY '
            || DBMS_ASSERT.ENQUOTE_NAME('&autoandes_password', FALSE)
            || ' DEFAULT TABLESPACE USERS QUOTA 100M ON USERS';
        EXECUTE IMMEDIATE 'GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE TO AUTOANDESDB';
    END IF;
END;
/
UNDEFINE autoandes_password
EXIT
